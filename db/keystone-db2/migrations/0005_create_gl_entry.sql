-- General ledger entries posted by the core for a business date. Reconciliation compares
-- these, per GL account and side, with the totals the batch derives from transactions.

CREATE TABLE KS.GL_ENTRY (
    GL_ENTRY_ID     BIGINT         NOT NULL,
    GL_ACCOUNT_NBR  CHAR(10)       NOT NULL,
    POSTING_DATE    DATE           NOT NULL,
    DEBIT_AMOUNT    DECIMAL(15,2)  NOT NULL DEFAULT 0,
    CREDIT_AMOUNT   DECIMAL(15,2)  NOT NULL DEFAULT 0,
    SOURCE_CODE     CHAR(4)        NOT NULL,
    BATCH_REF       VARCHAR(20),
    MEMO            VARCHAR(80),
    CREATED_TS      TIMESTAMP(6)   NOT NULL,
    CONSTRAINT PK_GL_ENTRY PRIMARY KEY (GL_ENTRY_ID),
    CONSTRAINT FK_GL_ENTRY_ACCOUNT FOREIGN KEY (GL_ACCOUNT_NBR) REFERENCES KS.GL_ACCOUNT (GL_ACCOUNT_NBR),
    CONSTRAINT CK_GL_ENTRY_AMOUNTS CHECK (
        DEBIT_AMOUNT >= 0 AND CREDIT_AMOUNT >= 0 AND (DEBIT_AMOUNT = 0 OR CREDIT_AMOUNT = 0))
);

CREATE INDEX KS.IX_GL_ENTRY_POSTING_DATE ON KS.GL_ENTRY (POSTING_DATE);
